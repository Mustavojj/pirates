    async saveUserData(immediate = false) {
        if (!this.tgUser || !this.isAuthenticated) return false;

        if (this._isSaving) {
            if (immediate) {
                let waited = 0;
                while (this._isSaving && waited < 3000) {
                    await new Promise(resolve => setTimeout(resolve, 50));
                    waited += 50;
                }
                if (this._isSaving) return false;
            } else {
                return true;
            }
        }

        this._isSaving = true;

        try {
            const updates = {};
            if (this._dirtyPower) updates.powerBalance = this.powerBalance;
            if (this._dirtyDogs) updates.dogsBalance = this.dogsBalance;
            if (this._dirtyGram) updates.gramBalance = this.gramBalance;
            if (this._dirtyQuests) updates.quests = this.quests;
            if (this._dirtyMining) {
                updates.miningActive = this.miningActive;
                updates.miningStartTime = this.miningStartTime;
                updates.miningEndTime = this.miningEndTime;
                updates.pendingDogsReward = this.pendingDogsReward;
            }

            if (Object.keys(updates).length === 0) {
                this._isSaving = false;
                return true;
            }

            const result = await this.fetchFromServer('/api/update-user', updates);

            if (result.error) {
                console.error('Save error:', result.error);
                this.showNotification('Error', this.t('save_error'), 'error');
                this.vibrate('error');
                this._isSaving = false;
                return false;
            }

            this._dirtyPower = false;
            this._dirtyDogs = false;
            this._dirtyGram = false;
            this._dirtyQuests = false;
            this._dirtyMining = false;

            return true;
        } catch (error) {
            if (error.message === 'Cooldown' || error.message === 'Banned' || error.message === 'New device' || error.message === 'Auth required' || error.message === 'Device error') {
                this._isSaving = false;
                return false;
            }
            console.error('Failed to save user data:', error);
            this.showNotification('Error', this.t('save_error'), 'error');
            this.vibrate('error');
            return false;
        } finally {
            this._isSaving = false;
        }
    }

